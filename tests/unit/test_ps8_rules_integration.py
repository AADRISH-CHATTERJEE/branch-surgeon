# 1. Default rules.yaml parses successfully
# ---------------------------------------------------------------------------

class TestDefaultRulesLoad:
    def test_loads_nonzero_rules(self, engine: RuleEngine, init_rules_yaml: Path):
        count = engine.load_rules(init_rules_yaml)
        assert count >= 3, f"Expected >=3 rules, got {count}"

    def test_rules_have_valid_categories(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        for rule in engine.rules:
            assert isinstance(rule.category, RuleCategory), (
                f"Rule '{rule.name}' has invalid category: {rule.category}"
            )

    def test_rules_have_conditions(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        for rule in engine.rules:
            assert isinstance(rule.conditions, list), (
                f"Rule '{rule.name}' conditions is not a list"
            )

    def test_rule_names(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        names = {r.name for r in engine.rules}
        assert "max-function-length" in names
        assert "max-file-length" in names
        assert "no-wildcard-imports" in names


