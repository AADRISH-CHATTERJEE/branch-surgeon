"""PS-8 Integration tests: rules.yaml parsing, violation detection, and error reporting.

Proves end-to-end that:
1. The default rules.yaml generated by `refactory init` is parseable.
2. RuleEngine loads > 0 rules from it.
3. Violations are detected when context matches.
4. Invalid category / malformed YAML raises a helpful ValueError.
5. Flat-dict conditions (legacy) are auto-migrated.
"""

