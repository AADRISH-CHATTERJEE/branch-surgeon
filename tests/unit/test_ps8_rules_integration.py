class TestJsonLoading:
    def test_json_rules_load(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        data = {
            "rules": [
                {
                    "name": "json-rule",
                    "category": "custom",
                    "severity": "info",
                    "conditions": [{"field": "branch_name", "operator": "matches", "pattern": "^main$"}],
                    "message": "Must be main",
                }
            ]
        }
        (rules_dir / "rules.json").write_text(json.dumps(data), encoding="utf-8")
        count = engine.load_rules(tmp_path)
        assert count == 1

    def test_invalid_json_raises(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.json").write_text("{{{bad", encoding="utf-8")
        with pytest.raises(ValueError, match="Cannot read"):
            engine.load_rules(tmp_path)


