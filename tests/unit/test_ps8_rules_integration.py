class TestFlatDictConditions:
    def test_flat_max_lines_migrated(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - name: legacy-func
                category: max_function_size
                severity: warning
                conditions:
                  max_lines: 50
                message: "Too long"
        """), encoding="utf-8")
        count = engine.load_rules(tmp_path)
        assert count == 1
        rule = engine.rules[0]
        assert len(rule.conditions) == 1
        assert rule.conditions[0].operator == "greater_than"
        assert rule.conditions[0].value == 50

    def test_flat_pattern_migrated(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - name: legacy-import
                category: forbidden_import
                severity: warning
                conditions:
                  pattern: "from .* import \\\\*"
                message: "No wildcards"
        """), encoding="utf-8")
        count = engine.load_rules(tmp_path)
        assert count == 1
        rule = engine.rules[0]
        assert len(rule.conditions) == 1
        assert rule.conditions[0].operator == "matches"


