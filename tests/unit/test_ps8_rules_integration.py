class TestViolationDetection:
    def test_max_function_violation(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        ctx = RuleContext({
            "function_sizes": {"my_func": 80},
            "file_sizes": {},
            "imports": [],
        })
        result = engine.evaluate(ctx)
        violations = [v for v in result.violations if v.rule_name == "max-function-length"]
        assert len(violations) >= 1, "Expected violation for 80-line function"

    def test_max_file_violation(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        ctx = RuleContext({
            "function_sizes": {},
            "file_sizes": {"big_module.py": 700},
            "imports": [],
        })
        result = engine.evaluate(ctx)
        violations = [v for v in result.violations if "big_module" in (v.file_path or v.message)]
        assert len(violations) >= 1, "Expected violation for 700-line file"

    def test_forbidden_import_violation(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        ctx = RuleContext({
            "function_sizes": {},
            "file_sizes": {},
            "imports": ["from utils import *"],
        })
        result = engine.evaluate(ctx)
        violations = [v for v in result.violations if "wildcard" in v.message.lower() or "import" in v.message.lower()]
        assert len(violations) >= 1, "Expected violation for wildcard import"

    def test_no_violations_for_clean_code(self, engine: RuleEngine, init_rules_yaml: Path):
        engine.load_rules(init_rules_yaml)
        ctx = RuleContext({
            "function_sizes": {"small_func": 10},
            "file_sizes": {"small.py": 50},
            "imports": ["import os"],
        })
        result = engine.evaluate(ctx)
        assert result.passed is True

    def test_blocking_flag_propagated(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - name: block-big-files
                category: max_file_size
                severity: error
                blocking: true
                conditions:
                  - field: file_size
                    operator: greater_than
                    value: 100
                message: "File too large"
        """), encoding="utf-8")
        engine.load_rules(tmp_path)
        ctx = RuleContext({"file_sizes": {"huge.py": 999}})
        result = engine.evaluate(ctx)
        assert result.passed is False
        assert result.blocking_violations >= 1


