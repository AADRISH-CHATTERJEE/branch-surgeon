class TestLoudValidationErrors:
    def test_invalid_category_raises(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - name: bad-rule
                category: nonexistent_category
                severity: warning
                conditions: []
                message: "bad"
        """), encoding="utf-8")
        with pytest.raises(ValueError, match="unknown category"):
            engine.load_rules(tmp_path)

    def test_invalid_conditions_type_raises(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - name: bad-cond
                category: custom
                severity: warning
                conditions: "a string"
                message: "bad"
        """), encoding="utf-8")
        with pytest.raises(ValueError, match="must be a list or mapping"):
            engine.load_rules(tmp_path)

    def test_missing_name_raises(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - category: custom
                severity: warning
                conditions: []
        """), encoding="utf-8")
        with pytest.raises(ValueError, match="all.*rules failed"):
            engine.load_rules(tmp_path)

    def test_partial_parse_warns_but_loads(self, engine: RuleEngine, tmp_path: Path):
        """If some rules parse and others fail, load the good ones."""
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              - name: good-rule
                category: custom
                severity: warning
                conditions: []
                message: "ok"
              - name: bad-rule
                category: INVALID_CAT
                severity: warning
                conditions: []
                message: "fails"
        """), encoding="utf-8")
        count = engine.load_rules(tmp_path)
        assert count == 1
        assert engine.rules[0].name == "good-rule"

    def test_rules_not_a_list_raises(self, engine: RuleEngine, tmp_path: Path):
        rules_dir = tmp_path / ".refactory"
        rules_dir.mkdir()
        (rules_dir / "rules.yaml").write_text(textwrap.dedent("""\
            rules:
              some_key: some_value
        """), encoding="utf-8")
        with pytest.raises(ValueError, match="must be a list"):
            engine.load_rules(tmp_path)


